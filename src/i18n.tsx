export const DICTS: Record<Lang, Dict> = { en, vi };

const Ctx = createContext<{ t: Dict; lang: Lang }>({ t: en, lang: "en" });

export function I18nProvider(props: { lang: Lang; children: ReactNode }) {
  return <Ctx.Provider value={{ t: DICTS[props.lang], lang: props.lang }}>{props.children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
